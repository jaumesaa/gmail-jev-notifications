import {readFileSync, writeFileSync} from 'node:fs';
const core = readFileSync('extension/lib/core.js', 'utf8').replace(/^export /gm, '');
const background = readFileSync('src/background.js', 'utf8').replace(/^import .*;\n/, '');
// Safari creates the classic background document; do not depend on its default charset.
const output = `// Generated by scripts/bundle.mjs. Edit src/background.js and extension/lib/core.js.\n(() => {\n'use strict';\n${core}\n${background}\n})();\n`.replace(/[^\x00-\x7f]/g, char => `\\u${char.charCodeAt(0).toString(16).padStart(4, '0')}`);
if (process.argv.includes('--check')) {
  if (readFileSync('extension/background.js', 'utf8') !== output) throw new Error('Background bundle is stale. Run node scripts/bundle.mjs.');
} else writeFileSync('extension/background.js', output);
